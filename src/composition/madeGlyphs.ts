/** Nine rows, five columns. Row 6 sits on the baseline. The last two rows descend. */
function art(body: string): string {
  const lines = body.replace(/^\n/, '').replace(/\s+$/, '').split('\n');
  if (lines.length !== 9 || lines.some((line) => line.length !== 5)) {
    throw new Error(`glyph rows ${lines.length}: ${lines.join('|')}`);
  }
  return lines.join('');
}

