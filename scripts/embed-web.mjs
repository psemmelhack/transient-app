import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const exported = path.join(root, '.embedded-export');
const out = path.join(root, 'embedded-web');

fs.rmSync(exported, { recursive: true, force: true });
const result = spawnSync('npx', ['expo', 'export', '--platform', 'web', '--output-dir', exported], {
  stdio: 'inherit',
  env: { ...process.env, CI: '1', EXPO_NO_TELEMETRY: '1' },
});
if (result.status !== 0) process.exit(result.status ?? 1);

let html = fs.readFileSync(path.join(exported, 'index.html'), 'utf8');
html = html.replace(/<base href="\/"\s*\/?>/, '<base href="./" />');
html = html.replace(/src="\/_expo\//g, 'src="_expo/');
html = html.replace(/<link rel="icon" href="\/favicon.ico"\s*\/?>/g, '');
html = html.replace(/<script>\s*if \('serviceWorker'[\s\S]*?<\/script>/, '');
if (!html.includes('Measure the moment.')) {
  console.error('The embedded page lost its description.');
  process.exit(1);
}

const jsMatch = html.match(/src="(_expo\/static\/js\/web\/[^"]+\.js)"/);
if (!jsMatch) {
  console.error('The web bundle script is missing from index.html.');
  process.exit(1);
}
const jsRel = jsMatch[1];
const jsBytes = fs.readFileSync(path.join(exported, jsRel));

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'index.html'), html);
fs.writeFileSync(path.join(out, 'app.webjs'), jsBytes);

const files = {
  'index.html': './index.html',
  [jsRel]: './app.webjs',
  'fonts.css': '../public/fonts.css',
  'manifest.webmanifest': '../public/manifest.webmanifest',
  'vendor/maplibre-gl.css': '../public/vendor/maplibre-gl.css',
};
for (const name of fs.readdirSync(path.join(root, 'public/fonts'))) {
  files[`fonts/${name}`] = `../public/fonts/${name}`;
}
for (const name of fs.readdirSync(path.join(root, 'public/icons'))) {
  files[`icons/${name}`] = `../public/icons/${name}`;
}

// Hash every packed file. A font, stylesheet, or HTML change has to bust the cache too.
const hash = createHash('sha256');
for (const key of Object.keys(files).sort()) {
  hash.update(key);
  hash.update('\0');
  hash.update(fs.readFileSync(path.resolve(out, files[key])));
  hash.update('\0');
}
const revision = hash.digest('hex').slice(0, 12);

const body = [
  '// Generated by scripts/embed-web.mjs. Do not edit.',
  'module.exports = {',
  `  revision: ${JSON.stringify(revision)},`,
  '  files: {',
  ...Object.entries(files).map(([key, req]) => `    ${JSON.stringify(key)}: require(${JSON.stringify(req)}),`),
  '  },',
  '};',
  '',
].join('\n');
fs.writeFileSync(path.join(out, 'manifest.js'), body);
fs.writeFileSync(
  path.join(root, 'src/native/packRevision.ts'),
  ['// Rewritten by scripts/embed-web.mjs. Do not edit.', `export const PACK_REVISION = ${JSON.stringify(revision)};`, ''].join('\n'),
);
fs.rmSync(exported, { recursive: true, force: true });
console.log(`embedded-web revision ${revision}`);
